import { jsPDF } from 'jspdf';

export interface ReceiptPayload {
  receipt_number: string;
  issued_at: string;
  invoice_number: string;
  billing_month: string;
  full_name: string;
  member_code: string;
  phone: string;
  room_number?: string | null;
  category_name?: string | null;
  amount_due: number;
  paid_amount: number;
  remaining_amount: number;
  amount: number;
  payment_date: string;
  payment_method: string;
  reference_id?: string;
}

export function downloadPaymentReceiptPdf(r: ReceiptPayload): void {
  const doc = new jsPDF({ unit: 'pt', format: 'a5' });
  doc.setFillColor(11, 31, 58);
  doc.rect(0, 0, 420, 74, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('DOT BOYS HOSTEL', 24, 32);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text('Building # D-399, Main 6th Road, Satellite Town, Rawalpindi', 24, 48);
  doc.text('Phone / WhatsApp: +92 305 9308333', 24, 61);

  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('OFFICIAL RENT PAYMENT RECEIPT', 24, 102);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  const rows: Array<[string, string]> = [
    ['Receipt No.', r.receipt_number || `PAY-${r.payment_date}`],
    ['Invoice No.', r.invoice_number],
    ['Billing Month', r.billing_month],
    ['Payment Date', r.payment_date],
    ['Resident Name', `${r.full_name} (${r.member_code})`],
    ['Room / Category', `${r.room_number || '-'} · ${r.category_name || '-'}`],
    ['Contact', r.phone],
    ['Payment Method', r.payment_method],
    ['Reference ID', r.reference_id || '-'],
  ];

  let y = 128;
  for (const [label, val] of rows) {
    doc.setTextColor(100, 116, 139);
    doc.text(label, 24, y);
    doc.setTextColor(15, 23, 42);
    doc.text(String(val), 150, y);
    y += 20;
  }

  doc.setDrawColor(203, 213, 225);
  doc.line(24, y + 6, 396, y + 6);
  y += 28;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('Amount Paid (This Transaction):', 24, y);
  doc.text(`Rs. ${Number(r.amount).toLocaleString('en-PK')}`, 280, y);

  y += 20;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.text('Total Invoice Due:', 24, y);
  doc.text(`Rs. ${Number(r.amount_due).toLocaleString('en-PK')}`, 280, y);

  y += 18;
  doc.text('Total Paid to Date:', 24, y);
  doc.text(`Rs. ${Number(r.paid_amount).toLocaleString('en-PK')}`, 280, y);

  y += 18;
  doc.setFont('helvetica', 'bold');
  doc.text('Remaining Balance:', 24, y);
  doc.text(`Rs. ${Number(r.remaining_amount).toLocaleString('en-PK')}`, 280, y);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.setTextColor(100, 116, 139);
  doc.text('Generated by DOT BOYS HOSTEL Management System (Asia/Karachi)', 24, 560);

  doc.save(`${r.receipt_number || 'receipt'}.pdf`);
}

export function downloadSummaryReportPdf(params: {
  title: string;
  headers: string[];
  rows: Array<Array<string | number>>;
  filename: string;
}): void {
  const doc = new jsPDF({ orientation: 'landscape', unit: 'pt', format: 'a4' });
  doc.setFillColor(11, 31, 58);
  doc.rect(0, 0, 842, 64, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(15);
  doc.text(`DOT BOYS HOSTEL — ${params.title}`, 28, 30);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(`Generated: ${new Date().toLocaleString('en-PK', { timeZone: 'Asia/Karachi' })} (PKT)`, 28, 48);

  let y = 92;
  const colWidth = Math.floor(786 / Math.max(1, params.headers.length));
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9.5);
  doc.setTextColor(11, 31, 58);
  params.headers.forEach((h, i) => {
    doc.text(String(h), 28 + i * colWidth, y);
  });
  doc.setDrawColor(203, 213, 225);
  doc.line(28, y + 6, 814, y + 6);
  y += 22;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(30, 41, 59);
  for (const row of params.rows) {
    if (y > 545) {
      doc.addPage();
      y = 44;
    }
    row.forEach((cell, i) => {
      doc.text(String(cell).slice(0, 32), 28 + i * colWidth, y);
    });
    y += 18;
  }

  doc.save(params.filename);
}
